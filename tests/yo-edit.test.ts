import { describe, it, expect } from 'vitest';
import { isYoEdit } from '@/lib/yo-edit';

describe('isYoEdit: правка только меняет е на ё', () => {
  it.each([
    ['ученого', 'учёного'],
    ['еще', 'ещё'],
    ['Еще', 'Ещё'],
    ['ее', 'её'],
    ['трех', 'трёх'],
    ['Все ее', 'Всё её'],
  ])('«%s» → «%s» — да', (a, b) => expect(isYoEdit(a, b)).toBe(true));

  it.each([
    ['качественая', 'качественная'],
    ['ситприн', 'ситпринт'],
    ['ученого', 'учёного,'],
    ['ученого', 'ученого'],
    ['ученого', 'учёнго'],
    ['ученый секретарь', 'учёный секретаря'],
    ['ё', 'е'],
    ['а', 'ё'],
  ])('«%s» → «%s» — нет', (a, b) => expect(isYoEdit(a, b)).toBe(false));
});
