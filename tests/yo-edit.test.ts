import { describe, it, expect } from 'vitest';
import { isYoEdit, stripAddedYo, stripYoReason, withoutYo } from '@/lib/yo-edit';
import type { Edit } from '@/lib/types';

describe('stripAddedYo: ё из предложения заменяется на е', () => {
  it.each([
    ['Разведчик сапер', 'Разведчик-сапёр', 'Разведчик-сапер'],
    ['Награжден Орденом', 'Награждён орденом', 'Награжден орденом'],
    ['н.п Соленое', 'н.п. Солёное', 'н.п. Соленое'],
    ['Роте Почетно-\nго Караула', 'роте почётно-\nго караула', 'роте почетно-\nго караула'],
    ['Школьные годы', 'Годы учёбы', 'Годы учебы'],
    ['ЧЕРНЫЙ', 'ЧЁРНЫЙ', 'ЧЕРНЫЙ'],
    ['ученого', 'учёного', 'ученого'],
  ])('«%s» → «%s» = «%s»', (a, b, want) => expect(stripAddedYo(a, b)).toBe(want));

  it('не трогает ё, которая уже есть в исходном слове', () => {
    expect(stripAddedYo('Фёдор сапер', 'Фёдор-сапёр')).toBe('Фёдор-сапер');
  });
});

describe('stripYoReason: из пояснения убирается требование ё', () => {
  it.each([
    ['Нужен дефис, как в очерке; профиль клиента: буква ё обязательна', 'Нужен дефис, как в очерке'],
    ['Буква ё обязательна по профилю клиента; почётное наименование части пишется с прописной', 'Почётное наименование части пишется с прописной'],
    ['Искажён топоним: в тексте биографии — Золотарёвка; также обязательна ё.', 'Искажён топоним: в тексте биографии — Золотарёвка'],
    ['Пропущена точка в сокращении; буква ё обязательна по профилю клиента', 'Пропущена точка в сокращении'],
    ['Тавтология: «школьные годы в школе».', 'Тавтология: «школьные годы в школе».'],
  ])('«%s»', (reason, want) => expect(stripYoReason(reason)).toBe(want));
});

describe('withoutYo: правки для дизайнера без замен на ё', () => {
  const mk = (original: string, suggested: string, reason: string) => ({ id: 1, spanStart: 5, spanEnd: 9, original, suggested, reason }) as Edit;

  it('убирает чистые замены е→ё', () => {
    expect(withoutYo([mk('ушел', 'ушёл', 'Профиль клиента: буква ё обязательна')])).toEqual([]);
  });

  it('в смешанной правке оставляет исправление и координаты', () => {
    const [e] = withoutYo([mk('Разведчик сапер', 'Разведчик-сапёр', 'Нужен дефис; профиль клиента: буква ё обязательна')]);
    expect(e).toMatchObject({ spanStart: 5, spanEnd: 9, original: 'Разведчик сапер', suggested: 'Разведчик-сапер', reason: 'Нужен дефис' });
  });

  it('не меняет переданные правки', () => {
    const src = mk('Разведчик сапер', 'Разведчик-сапёр', 'Нужен дефис');
    withoutYo([src]);
    expect(src.suggested).toBe('Разведчик-сапёр');
  });
});

describe('isYoEdit: правка только меняет е на ё', () => {
  it.each([
    ['ученого', 'учёного'],
    ['еще', 'ещё'],
    ['Еще', 'Ещё'],
    ['ее', 'её'],
    ['трех', 'трёх'],
    ['Все ее', 'Всё её'],
  ])('«%s» → «%s» — да', (a, b) => expect(isYoEdit(a, b)).toBe(true));

  it.each([
    ['качественая', 'качественная'],
    ['ситприн', 'ситпринт'],
    ['ученого', 'учёного,'],
    ['ученого', 'ученого'],
    ['ученого', 'учёнго'],
    ['ученый секретарь', 'учёный секретаря'],
    ['ё', 'е'],
    ['а', 'ё'],
  ])('«%s» → «%s» — нет', (a, b) => expect(isYoEdit(a, b)).toBe(false));
});
